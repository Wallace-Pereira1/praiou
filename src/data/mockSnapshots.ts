import type { BeachSnapshot, HourlyForecastPoint } from '../types';

function makeHourly(
  baseTemp: number,
  baseRainProb: number,
  baseWave: number,
  pattern: 'sunny' | 'clearing' | 'windy' | 'rainy'
): HourlyForecastPoint[] {
  const hours = [
    '14:00',
    '15:00',
    '16:00',
    '17:00',
    '18:00',
    '19:00',
    '20:00',
    '21:00',
    '22:00',
    '23:00',
    '00:00',
    '01:00',
  ];
  return hours.map((timeLabel, idx) => {
    const tempDelta = idx < 2 ? 0 : -Math.round(idx * 0.55);
    const rainDelta =
      pattern === 'rainy'
        ? Math.min(95, baseRainProb + idx * 2)
        : pattern === 'clearing'
          ? Math.max(5, baseRainProb - idx * 4)
          : Math.min(45, baseRainProb + (idx > 6 ? 10 : 0));

    const condition =
      rainDelta >= 60
        ? 'rain'
        : pattern === 'sunny' && idx < 5
          ? 'sun'
          : rainDelta >= 30 || idx >= 5
            ? 'cloudy'
            : 'partly_cloudy';

    return {
      timeLabel,
      condition,
      temperatureC: baseTemp + tempDelta,
      rainProb: Math.max(0, Math.min(100, rainDelta)),
      waveHeightM: Number(Math.max(0.4, baseWave + (idx % 3 === 0 ? 0.1 : 0)).toFixed(1)),
    };
  });
}

